CREATE DATABASE otpdb;
CREATE USER otp WITH ENCRYPTED PASSWORD 'otp123';
GRANT ALL PRIVILEGES ON DATABASE otpdb TO otp;


CREATE TABLE IF NOT EXISTS otp_codes (
    id BIGSERIAL PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    code_hash VARCHAR(255) NOT NULL,
    status VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    verified_at TIMESTAMP
);

GRANT USAGE ON SCHEMA public TO otp;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE otp_codes TO otp;
GRANT USAGE, SELECT ON SEQUENCE otp_codes_id_seq TO otp;
ALTER TABLE otp_codes DROP COLUMN code;

